#!/usr/bin/env python3
"""Generate the E2 srtctl recipes (K3.1 PD: 1 prefill node + an EP16 decode on two nodes, MoRIIO KV) from the
1P1D recipe that ran on smci355 (k31-umbp-20261112/configs/srtctl-pd/simplecpu_1p1d_c128.yaml, the colleague's
disagg-ms.yaml ported to this cluster).

  make_e2.py  ->  configs/e2_pd_{write,read}.yaml (EP16 decode), configs/e2_pd32_{write,read}.yaml (EP32 decode)

Changes against that recipe:
  prefill  MoRIIO only (no SimpleCPU offload, so no hugepages host_setup), read_mode per recipe
  decode   2 (or 4) nodes, data-parallel-size 2 (4) x TP8 DCP8 = EP16 (EP32) (enable-expert-parallel, mori_low_latency),
           DSpark with 7 draft tokens (qlen 8), max-num-seqs 128 per DP rank, max-num-batched-tokens 1024, FULL graphs
           at multiples of 8 up to 1024, MoRI EP RDMA env of the microbenchmarks, torch profiler into /logs/prof
  benchmark manual: srtctl brings the servers up and holds them; e2e/e2.sh drives load, IO windows and profiles
"""
import copy
import json
import os

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = "/apps/yutongwu/store-vllm/k31-umbp-20261112/configs/srtctl-pd/simplecpu_1p1d_c128.yaml"
SPEC_K, SPEC_ACC, MAX_SEQS = 7, 3.0, 128
EP_ENV = {
    "MORI_RDMA_DEVICES": ",".join(f"ionic_{i}" for i in range(8)),
    "MORI_DEVICE_NIC": "ionic",
    "MORI_IB_GID_INDEX": "1",
    "MORI_DISABLE_IONIC_CCQE": "1",
    "MORI_IB_ENABLE_RELAXED_ORDERING": "0",
    "MORI_ENABLE_RAIL_ONLY": "1",
    "MORI_SHMEM_HEAP_SIZE": "8G",
    "MORI_ENABLE_SDMA": "0",
    "MORI_SOCKET_IFNAME": "enp81s0f1",
    "NCCL_SOCKET_IFNAME": "enp81s0f1",
    "NCCL_IB_HCA": ",".join(f"ionic_{i}" for i in range(8)),
    "NCCL_IB_GID_INDEX": "1",
    "NCCL_IB_TC": "104",
}


def sizes(q, top):
    s = {q * i for i in (1, 2, 4, 8, 16, 24, 32, 48, 64, 80, 96, 112, 128) if q * i <= top}
    return sorted(s | {top})


def make(read_mode, dnodes):
    r = yaml.safe_load(open(SRC))
    out = copy.deepcopy(r)
    mode = "read" if read_mode else "write"
    out["name"] = f"k31-pd-ep{8 * dnodes}-{mode}"
    out.pop("host_setup", None)
    out["environment"] = {"KV_P2P_TRANSFER": "moriio", "K31_CLEAN_RUN_ID": "k31-ms-1114"}
    spec = json.loads(r["roles"]["decode"]["args"]["speculative-config"])
    spec.update(num_speculative_tokens=SPEC_K, synthetic_acceptance_length=SPEC_ACC)

    p = out["roles"]["prefill"]
    p["args"]["kv-transfer-config"] = json.dumps({
        "kv_connector": "MoRIIOConnector", "kv_role": "kv_producer", "kv_load_failure_policy": "fail",
        "kv_connector_extra_config": {"backend": "rdma", "read_mode": read_mode, "defer_timeout": 300}})
    p["args"]["speculative-config"] = json.dumps(spec)
    p["env"].pop("K31_SIMPLECPU_OBSERVER", None)

    d = out["roles"]["decode"]
    d["nodes"] = dnodes
    d["gpus"] = 8 * dnodes
    a = d["args"]
    q = SPEC_K + 1
    top = MAX_SEQS * q
    a.update({
        "data-parallel-size": dnodes,
        "enable-expert-parallel": True,
        "all2all-backend": "mori_low_latency",
        "gpu-memory-utilization": 0.85,
        "max-num-seqs": MAX_SEQS,
        "max-num-batched-tokens": top,
        "compilation-config": json.dumps({"mode": 3, "cudagraph_mode": "FULL_AND_PIECEWISE", "max_cudagraph_capture_size": top,
                                          "custom_ops": ["+fused_rms_norm_gated"], "cudagraph_capture_sizes": sizes(q, top)},
                                         separators=(",", ":")),
        "speculative-config": json.dumps(spec),
        "kv-transfer-config": json.dumps({
            "kv_connector": "MoRIIOConnector", "kv_role": "kv_consumer", "kv_load_failure_policy": "fail",
            "kv_connector_extra_config": {"backend": "rdma", "read_mode": read_mode}}),
        "profiler-config": json.dumps({"profiler": "torch", "torch_profiler_dir": "/logs/prof", "torch_profiler_with_stack": False,
                                       "torch_profiler_use_gzip": True, "torch_profiler_dump_cuda_time_total": False,
                                       "max_iterations": 20}),
    })
    d["env"].update(EP_ENV)
    out["benchmark"] = {"type": "manual"}
    return out, mode


if __name__ == "__main__":
    # e2_pd_*: EP16 decode on two nodes (3-node jobs); e2_pd32_*: EP32 decode on four (5-node jobs, the Moonshot case:
    # DP4 x 128 sequences = global batch 512 at qlen 8)
    for dnodes, tag in ((2, "pd"), (4, "pd32")):
        for rm in (False, True):
            cfg, mode = make(rm, dnodes)
            path = os.path.join(HERE, f"e2_{tag}_{mode}.yaml")
            with open(path, "w") as f:
                f.write(f"# generated by configs/make_e2.py from {SRC}\n")
                yaml.safe_dump(cfg, f, sort_keys=False, width=200)
            print(path)
